const resources = Object.fromEntries(
  languageOptions.map(({ code }) => [
    code,
    { translation: { ...translations[code], ...pageCopy[code], ...demoTranslations[code] } },
  ]),
);

function getInitialLanguage(): LanguageCode {
  if (typeof window === 'undefined') return 'en';

  try {
    const languageFromUrl = new URLSearchParams(window.location.search).get('lang');
    if (languageOptions.some(({ code }) => code === languageFromUrl)) {
      return languageFromUrl as LanguageCode;
    }
    const savedLanguage = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return languageOptions.some(({ code }) => code === savedLanguage)
      ? (savedLanguage as LanguageCode)
      : 'en';
  } catch {
    return 'en';
  }
}

function syncDocumentLanguage(language: string) {
  if (typeof document === 'undefined') return;
  const normalizedLanguage = languageOptions.some(({ code }) => code === language) ? language : 'en';
  document.documentElement.lang = normalizedLanguage;
  document.documentElement.dir = normalizedLanguage === 'ar' ? 'rtl' : 'ltr';
}

void i18n.use(initReactI18next).init({
  resources,
  lng: getInitialLanguage(),
  fallbackLng: 'en',
  supportedLngs: languageOptions.map(({ code }) => code),
  keySeparator: false,
  interpolation: { escapeValue: false },
  returnEmptyString: false,
});

i18n.on('languageChanged', syncDocumentLanguage);
syncDocumentLanguage(getInitialLanguage());

export default i18n;
